import { jsPDF } from "jspdf";
import autoTable from "jspdf-autotable";
import {
  formatPercent,
  formatPesos,
  reportFileName,
  type GeneratedReport,
} from "./reports";

/**
 * Rendering of the two generated reports as a printable PDF. The content
 * mirrors the CSV builders in `lib/reports.ts` (same rows, same totals), so a
 * filed PDF and the ledger agree line for line.
 */

const MARGIN = 14;
const LINE_HEIGHT = 4.6;

const TITLES: Record<GeneratedReport["kind"], string> = {
  liquidation: "SK-Ledge Liquidation Report",
  "financial-summary": "SK-Ledge Financial Summary",
};

function headerLines(report: GeneratedReport): string[] {
  const { meta } = report;
  return [
    `Barangay: ${meta.barangay}`,
    `Period: ${meta.periodStart} to ${meta.periodEnd}`,
    `Generated by: ${meta.generatedBy}`,
    `Generated at: ${meta.generatedAt}`,
    `Receipt attachments: ${meta.includeReceipts ? "Included" : "Excluded"}`,
  ];
}

/** Draw the title block and return the y coordinate the table should start at. */
function drawHeader(doc: jsPDF, report: GeneratedReport): number {
  const pageWidth = doc.internal.pageSize.getWidth();
  let y = MARGIN + 4;

  doc.setFont("helvetica", "bold");
  doc.setFontSize(15);
  doc.text(TITLES[report.kind], MARGIN, y);
  y += 8;

  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  for (const line of headerLines(report)) {
    doc.text(line, MARGIN, y);
    y += LINE_HEIGHT;
  }

  // A rule under the header keeps printed and PDF copies looking the same.
  doc.setDrawColor(180);
  doc.setLineWidth(0.2);
  doc.line(MARGIN, y - 1, pageWidth - MARGIN, y - 1);

  return y + 3;
}

function drawNotes(doc: jsPDF, notes: readonly string[]): void {
  if (notes.length === 0) return;

  const lastTable = (
    doc as jsPDF & { lastAutoTable?: { finalY: number } }
  ).lastAutoTable;
  let y = (lastTable?.finalY ?? MARGIN) + 8;
  const pageHeight = doc.internal.pageSize.getHeight();
  const pageWidth = doc.internal.pageSize.getWidth();

  doc.setFont("helvetica", "italic");
  doc.setFontSize(8);
  for (const note of notes) {
    for (const line of doc.splitTextToSize(note, pageWidth - MARGIN * 2)) {
      if (y > pageHeight - MARGIN) {
        doc.addPage();
        y = MARGIN;
      }
      doc.text(line, MARGIN, y);
      y += LINE_HEIGHT;
    }
  }
}

function drawPageNumbers(doc: jsPDF): void {
  const pages = doc.getNumberOfPages();
  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();

  for (let page = 1; page <= pages; page += 1) {
    doc.setPage(page);
    doc.setFont("helvetica", "normal");
    doc.setFontSize(7);
    doc.setTextColor(120);
    doc.text(
      `SK-Ledge • generated locally from ledger records • page ${page} of ${pages}`,
      pageWidth / 2,
      pageHeight - 6,
      { align: "center" },
    );
    doc.setTextColor(0);
  }
}

const tableTheme = {
  styles: { fontSize: 7.5, cellPadding: 1.6, overflow: "linebreak" as const },
  headStyles: { fillColor: [45, 55, 72] as [number, number, number], fontSize: 7.5 },
  margin: { left: MARGIN, right: MARGIN },
};

export function buildReportPdf(report: GeneratedReport): jsPDF {
  const doc = new jsPDF({ unit: "mm", format: "a4", orientation: "portrait" });
  const notes: string[] = [];
  let cursor = drawHeader(doc, report);

  if (report.kind === "liquidation") {
    autoTable(doc, {
      ...tableTheme,
      startY: cursor,
      head: [
        [
          "Date",
          "DV / Reference",
          "Payee",
          "Purpose",
          "Category",
          "Amount (PHP)",
          "Compliance",
          "Receipts",
        ],
      ],
      body: report.rows.map((row) => [
        row.date,
        row.dvNumber,
        row.payee,
        row.purpose,
        row.category,
        formatPesos(row.amountCentavos),
        row.complianceStatus,
        row.receipts.length === 0
          ? "—"
          : row.receipts.map((receipt) => receipt.fileName).join("\n"),
      ]),
      foot: [
        [
          "TOTAL",
          "",
          "",
          "",
          "",
          formatPesos(report.totalCentavos),
          "",
          String(report.receiptCount),
        ],
      ],
      footStyles: { fillColor: [237, 242, 247] as [number, number, number], textColor: 20 },
      columnStyles: {
        0: { cellWidth: 18 },
        1: { cellWidth: 22 },
        2: { cellWidth: 30 },
        3: { cellWidth: 42 },
        4: { cellWidth: 22 },
        5: { cellWidth: 20, halign: "right" },
        6: { cellWidth: 20 },
      },
    });
    cursor = (doc as jsPDF & { lastAutoTable: { finalY: number } }).lastAutoTable
      .finalY;

    if (report.missingReceipts !== null && report.missingReceipts > 0) {
      notes.push(
        `${report.missingReceipts} expense ${report.missingReceipts === 1 ? "entry has" : "entries have"} no filed receipt.`,
      );
    }
  } else {
    const { totals } = report;

    autoTable(doc, {
      ...tableTheme,
      startY: cursor,
      head: [["Metric", "Value"]],
      body: [
        ["Total Allocated (PHP)", formatPesos(totals.allocatedCentavos)],
        ["Total Expenses (PHP)", formatPesos(totals.expenseCentavos)],
        ["Total Contract Awards (PHP)", formatPesos(totals.awardCentavos)],
        [
          "Remaining Balance, Allocated − Expenses (PHP)",
          formatPesos(totals.remainingCentavos),
        ],
        ["Budget Utilization", formatPercent(totals.utilization)],
      ],
      columnStyles: { 1: { halign: "right", cellWidth: 40 } },
    });
    cursor = (doc as jsPDF & { lastAutoTable: { finalY: number } }).lastAutoTable
      .finalY +
      8;

    autoTable(doc, {
      ...tableTheme,
      startY: cursor,
      head: [["Expense Category", "Amount (PHP)", "Share of Expenses"]],
      body: report.categories.map((category) => [
        category.label,
        formatPesos(category.amountCentavos),
        formatPercent(category.share),
      ]),
      columnStyles: {
        1: { halign: "right", cellWidth: 32 },
        2: { halign: "right", cellWidth: 34 },
      },
    });
  }

  if (report.truncated) {
    notes.push(
      "Note: the selected period has 500 or more ledger records. This report covers only the 500 most recent records; narrow the date range for a complete filing.",
    );
  }

  drawNotes(doc, notes);
  drawPageNumbers(doc);

  return doc;
}

export interface TablePdfOptions {
  fileName: string;
  title: string;
  subtitle?: readonly string[];
  head: readonly string[];
  rows: readonly (readonly (string | number)[])[];
  rightAligned?: readonly number[];
  notes?: readonly string[];
}

/** One-page-or-more PDF table, used by the reports that are not built by `buildReport`. */
export function downloadTablePdf({
  fileName,
  title,
  subtitle = [],
  head,
  rows,
  rightAligned = [],
  notes = [],
}: TablePdfOptions): void {
  const doc = new jsPDF({ unit: "mm", format: "a4", orientation: "portrait" });
  const pageWidth = doc.internal.pageSize.getWidth();

  doc.setFont("helvetica", "bold");
  doc.setFontSize(15);
  doc.text(title, MARGIN, MARGIN + 4);

  let y = MARGIN + 12;
  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  for (const line of subtitle) {
    doc.text(line, MARGIN, y);
    y += LINE_HEIGHT;
  }

  doc.setDrawColor(180);
  doc.setLineWidth(0.2);
  doc.line(MARGIN, y - 1, pageWidth - MARGIN, y - 1);

  autoTable(doc, {
    ...tableTheme,
    startY: y + 2,
    head: [head.map(String)],
    body: rows.map((row) => row.map((cell) => String(cell))),
    columnStyles: Object.fromEntries(
      rightAligned.map((index) => [index, { halign: "right" as const }]),
    ),
  });

  drawNotes(doc, notes);
  drawPageNumbers(doc);

  doc.save(fileName);
}

/** Trigger the browser download for a generated report as a PDF. */
export function downloadReportPdf(report: GeneratedReport): void {
  buildReportPdf(report).save(
    reportFileName(
      report.kind,
      report.meta.barangay,
      report.meta.periodStart,
      report.meta.periodEnd,
    ),
  );
}
